def log_query(q, ans):
    """每次问答落 query_log，支撑可观测与回放（失败不影响回答）。"""
    try:
        import sqlite3
        from datetime import datetime
        con = sqlite3.connect(DB_PATH)
        ver = ans.get("verification", {}) or {}
        con.execute("""INSERT INTO query_log
            (ts,q,mode,role,risk,confidence,abstain,top_ids,refs,
             verification_ok,warnings,verdict,model) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)""",
            (datetime.now().strftime("%Y-%m-%d %H:%M:%S"), q, ans.get("mode"),
             ans.get("routed"), ans.get("risk"), ans.get("confidence"),
             1 if ans.get("abstain") else 0,
             json.dumps(next((s.get("top_ids", []) for s in ans.get("stage_trace", [])
                              if s.get("stage") == "retrieve"), []), ensure_ascii=False),
             json.dumps(ans.get("refs", []), ensure_ascii=False),
             1 if ver.get("ok") else 0,
             json.dumps(ver.get("warnings", []), ensure_ascii=False),
             (ans.get("audit", {}) or {}).get("verdict", ""),
             "local" if not (LLM.get("enabled") and LLM.get("api_key")) else "llm"))
        con.commit()
        con.close()
    except Exception:
        pass


