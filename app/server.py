def examples_payload():
    """返回兼容旧版的 examples 数组 + v3 分组结构。"""
    items = [r for r in RULES if r.get("q")]
    groups = []
    for g in EXAMPLE_GROUPS:
        if g["id"] == "hot":
            picked = [r for rid in FEATURED_IDS for r in items if r["id"] == rid]
        else:
            picked = [r for r in items
                      if RULE_GROUP.get(r["id"], ROLE_FALLBACK_GROUP.get(r["role"], "tax")) == g["id"]]
        groups.append({
            "id": g["id"], "label": g["label"], "icon": g["icon"], "desc": g["desc"],
            "items": [{"id": r["id"], "q": r["q"], "role": r["role"], "risk": r["risk"]} for r in picked],
        })
    return {"examples": [r["q"] for r in items[:14]], "groups": groups,
            "total": len(items)}


