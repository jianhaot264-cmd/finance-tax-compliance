def build_llm_context(q, mode="standard"):
    """v6：分阶段上下文 = 精编引用 + 多路检索命中 + 权威逐字法条 + 概念解读层 + 角色化指令。

    mode=deep 时额外注入概念卡六段式内容与易混淆/门槛矩阵，并切换为深度解读 system prompt。
    """
    deep = mode == "deep"
    local = ask_local(q, mode=mode)
    v5 = RETRIEVER.retrieve(q, mode="v5", topk=6)
    ids = list(dict.fromkeys(list(local["refs"])[:4] + [h["id"] for h in v5["hits"]]))[:6]
    blocks = []
    for eid in ids:
        e = ENTRY_MAP.get(eid)
        if not e:
            continue
        f = e["fields"]
        blocks.append(
            f"【{e['title']}】（时效性：{e['status']}；层级：{e.get('tier', '')}）\n"
            f"文号：{f.get('文号', '') or e.get('doc_no', '')}；公布/施行：{f.get('公布/施行', '')}\n"
            f"核心条款：{f.get('核心条款', '')[:700]}\n"
            f"合规要点：{f.get('合规要点', '')[:500]}"
        )
    # 权威逐字法条注入（回库确认现行有效）
    try:
        import sqlite3
        con = sqlite3.connect(DB_PATH)
        hit = set(ids)
        n = 0
        for eid, law, art, verb in con.execute(
                "SELECT entry_id,law_name,article_no,verbatim FROM article_text"):
            if eid in hit and n < 6:
                blocks.append(f"【权威逐字法条 · {law} {art}】（回库核验：现行有效）\n{verb[:700]}")
                n += 1
        con.close()
    except Exception:
        pass
    # 法条原文 vs 现行口径的判定规则必须随上下文注入
    trap = ENTRY_MAP.get("24-24.7")
    if trap:
        blocks.append("【判定规则 · 法条原文 vs 现行执行口径】\n" +
                      (trap.get("fields", {}).get("核心条款", "") or "")[:600])
    if not blocks:
        blocks.append("（知识库未命中任何条目：请如实告知用户知识库暂无收录，建议咨询 12366 或主管税务机关，不得编造。）")
    dp = local.get("deep") if deep else None
    if dp and dp.get("concepts"):
        blocks.append("【概念解读层 · 本轮匹配】\n" + "\n".join(
            f"{c['code']} {c['name']}：{deep_dive.BY_ID.get(c['id'], {}).get('definition', '')}"
            for c in dp["concepts"]))
        for t in dp.get("thresholds", [])[:5]:
            blocks.append(f"【边界门槛】{t.get('value','')}｜{t.get('scope','')}｜"
                          f"生效 {t.get('effective','')}｜例外 {t.get('edge','')}")
    context_text = "\n\n".join(blocks)
    sys_prompt = orchestrator.stage_system_prompt(
        SYSTEM_PROMPT, local["routed"],
        "先按结论→依据→风险与合规提示输出；引用须来自上下文；"
        "若上下文中出现「法条原文」与「后续公告口径」不一致，以现行执行口径为准并说明依据。")
    if deep:
        sys_prompt = deep_dive.deep_system_prompt(sys_prompt, dp)
    return {
        "q": q,
        "mode": mode,
        "deep": dp if deep else None,
        "routed": local["routed"],
        "role": local["role"],
        "risk": local["risk"],
        "refs": ids,
        "retrieval": {"mode": "v5", "confidence": v5["confidence"],
                      "abstain": v5["abstain"], "top": [h["id"] for h in v5["hits"]]},
        "stage_trace": local.get("stage_trace", []),
        "verification": local.get("verification", {}),
        "system_prompt": sys_prompt + "\n\n=== 知识库上下文（核验日期 2026-11-07，回答只能依据以下内容） ===\n" + context_text,
        "fallback": local,
        "fallback_disclaimer": "本地知识库答案，仅供合规参考；正式用途请以官方原文为准。",
        "disclaimer": "回答由云端大模型基于本地知识库（核验日期 2026-11-07）生成，仅供合规参考，不构成税务师/律师专业意见。",
    }


def provenance_block(refs, mode=""):
    """P0-2：每个回答自动挂载溯源四要素（法条编号 + 适用日期 + 地区口径 + 快照时间）。"""
    law_bits, eff_bits = [], []
    for r in (refs or [])[:4]:
        e = ENTRY_MAP.get(r)
        if not e:
            continue
        doc = e.get("doc_no") or e.get("fields", {}).get("文号", "") or ""
        title = e.get("title", "")
        bit = f"{title}" + (f"（{doc}）" if doc else "")
        if bit not in law_bits:
            law_bits.append(bit)
        eff = e.get("effective_date") or e.get("fields", {}).get("公布/施行", "")
        if eff and eff not in eff_bits:
            eff_bits.append(f"{title[:16]}：{eff}")
    snapshot = KB.get("verified_at", "") or ""
    return {"type": "tips", "title": "溯源四要素（法条编号 · 适用日期 · 地区口径 · 快照时间）",
            "items": [
                f"法条编号：{('；'.join(law_bits[:3])) or '本轮引用见依据栏'}",
                f"适用日期：{('；'.join(eff_bits[:2])) or '以引用文件公布/施行日为准'}",
                "地区口径：全国统一口径；广东省/大湾区/地市差异须按属地公告执行（见广东专章条目）",
                f"政策快照时间：{snapshot or '见知识库版本'}（核验截止日；此后政策变动须以官方最新公告为准）",
            ]}


def build_calc_answer(cr):
    """把确定性计算结果包装成标准回答结构（P0 红线：LLM 不产出数值）。"""
    steps_html = cr.get("steps") or []
    items = [f"{st.get('label','')}: {st.get('expr','')} = {st.get('value','')}"
             for st in steps_html]
    basis_items = []
    for b in cr.get("basis") or []:
        bit = f"《{b['name']}》" if not b["name"].startswith("《") else b["name"]
        if b.get("article"):
            bit += f" {b['article']}"
        if b.get("effective"):
            bit += f"（{b['effective']}）"
        bit += f"〔{b.get('region','全国')}〕"
        basis_items.append(bit)
    caveats = cr.get("caveats") or []
    ans = {
        "role": ROLES["tax-filing-specialist"],
        "routed": "tax-filing-specialist",
        "risk": "low",
        "mode": "calc",
        "matched_q": "",
        "refs": [],
        "calc": cr,
        "sections": [],
    }
    ans["sections"].append({
        "type": "conclusion",
        "text": f"【确定性计算结果】{cr['formula']} = **{cr['value']} 元**（本地引擎算出，非大模型生成）",
    })
    ans["sections"].append({"type": "basis", "title": "计算依据（法条/文件）", "items": basis_items})
    if items:
        ans["sections"].append({"type": "retrieval", "title": "分步算式", "items": items})
    if caveats:
        ans["sections"].append({"type": "tips", "title": "适用条件与限制", "items": caveats})
    ans["sections"].append({
        "type": "tips", "title": "溯源四要素",
        "items": [
            f"法条编号：{'；'.join((b.get('article') or b.get('name','')) for b in (cr.get('basis') or [])[:3]) or '见上'}",
            f"适用日期：{cr.get('snapshot', '')} 核验口径（政策快照时间）",
            "地区口径：全国统一口径，属地差异（如城建税率、契税省级幅度）须另核当地公告",
            f"计算引擎：{cr.get('engine','tax_calc')} · 确定性脚本，不产生臆测数值",
        ],
    })
    ans["sections"].append({
        "type": "escalate",
        "text": "🧮 本结果由本地确定性计算引擎产出（禁止大模型算税）。"
                "实际申报前请核对适用条件与属地口径；本工具仅用于辅助合规自查，不构成专业税务/法律意见。",
    })
    ans["confidence"] = 1.0
    ans["abstain"] = False
    return ans


def ask_local(q, mode="standard"):
    """v6：**计算类问题 → 确定性计算引擎（LLM 不出数值）**；
    其余走规则精编 → 检索兜底 → 弃答 → 五阶段编排 → 深度解读。"""
    # ---- P0 红线：计算类问题只走本地确定性脚本 ----
    try:
        cr = tax_calc_run(q)
    except Exception:
        cr = None
    if cr is not None and getattr(cr, "get", lambda k, d=None: d)("ok", True):
        return build_calc_answer(cr)
    # ---- 意图不明 → 选项式澄清追问（不泛泛作答）；精确命中精编问句的直接走规则 ----
    clarify = None if any(r.get("q") == q for r in RULES) else detect_clarify(q)
    if clarify:
        return {
            "role": ROLES["lead"], "routed": "lead", "risk": "low",
            "mode": "clarify", "matched_q": "", "refs": [],
            "clarify": clarify, "confidence": 0.0, "abstain": False,
            "sections": [{
                "type": "clarify",
                "title": "先确认你的问题方向",
                "text": clarify["question"],
                "options": clarify["options"],
            }],
        }
    role = route_role(q)
    risk = assess_risk(q)
    v5 = RETRIEVER.retrieve(q, mode="v5", topk=8)

    # Stage 3 精编：规则答案库仍为最高置信来源（必要条件 + 关键词长度加权）
    # v6：完全一致的示例问法优先命中其精编答案（前端点击示例即走此路径），
    #      避免被含短关键词的泛化规则抢答而输出不相关结论。
    best_rule, best_score = None, 0
    exact = next((r for r in RULES if r.get("q") and r["q"] == q), None)
    if exact:
        best_rule, best_score = exact, 10 ** 6
    else:
        for r in RULES:
            if r.get("must") and not any(k in q for k in r["must"]):
                continue
            sc = sum(len(k) for k in r["kw"] if k in q)
            if sc > best_score:
                best_rule, best_score = r, sc
    # v6：不可完成意图优先弃答（即使命中泛化规则，也不硬答穷举/无数据精算）
    force_abstain = ""
    if EXHAUSTIVE_RE.search(q):
        force_abstain = "exhaustive"
        best_rule = None
    elif NO_DATA_RE.search(q):
        force_abstain = "no_data"
        best_rule = None
    elif OUT_OF_SCOPE_RE.search(q):
        force_abstain = "out_of_scope"
        best_rule = None

    # 审计/核验意图问句（「能直接用吗」「听谁的」）无论命中哪条规则，均路由合规审计岗
    routed_role = (best_rule["role"] if best_rule else role)
    if AUDIT_INTENT_RE.search(q):
        routed_role = "compliance-auditor"
    ans = {"role": ROLES[routed_role],
           "routed": routed_role,
           "risk": best_rule.get("risk", risk) if best_rule else risk,
           "mode": "rule" if best_rule else "retrieval",
           "matched_q": best_rule["q"] if best_rule else "",
           "refs": [], "sections": []}
    if best_rule:
        ans["refs"] = valid_refs(best_rule["refs"])
        ans["sections"].append({"type": "conclusion", "text": best_rule["conclusion"]})
        ans["sections"].append({
            "type": "basis",
            "items": [{"text": t, "ref": rid if rid in ENTRY_MAP else ""} for t, rid in best_rule["basis"]],
        })
        if best_rule["tips"]:
            ans["sections"].append({"type": "tips", "items": best_rule["tips"]})
    elif force_abstain or v5["abstain"] or not v5["hits"]:
        # 低置信 / 不可完成意图弃答：不硬答、不把检索噪声当答案
        ans["mode"] = "abstain"
        if force_abstain == "exhaustive":
            concl = ("该问题要求逐一穷举全部国家 / 地市 / 条款，超出知识库可核验范围，无法给出完整清单。"
                     "本应用不作选择性列举以免误导；请按官方数据库或主管税务机关提供的完整目录查询。")
        elif force_abstain == "no_data":
            concl = ("缺少计税所必需的销售额、收入、成本或期间等数据，无法计算确定金额。"
                     "请补充具体数据与所属期后再提问；本应用不基于假设数字给出税额。")
        elif force_abstain == "out_of_scope":
            concl = ("该问题涉及的地理区域或法域不在中国税法适用范围内（如火星、公海、虚拟国家等），"
                     "无法给出税务结论。请确认注册地/经营地是否在中国境内，或是否与中国签有生效的税收协定。")
        else:
            concl = ("知识库暂无可靠收录，无法给出确定结论。本问题未命中精编答案库，检索置信度亦低于阈值；"
                     "建议咨询 12366、主管税务机关或回查官方发布原文，本应用不作猜测补全。")
        ans["sections"].append({"type": "conclusion", "text": concl})
        ans["sections"].append({
            "type": "tips",
            "items": ["可尝试补充文号、税种、年份、地域或计税数据后重新提问",
                      "涉及地方细则、逐国协定条款或个案批复时，须按 SOURCES-CHANNELS.md 的 SOP 属地确认"],
        })
    else:
        hits = [ENTRY_MAP[h["id"]] for h in v5["hits"][:6] if h["id"] in ENTRY_MAP]
        ans["sections"].append({
            "type": "retrieval",
            "title": "知识库检索命中（多路召回 + 重排）",
            "items": [entry_summary(e["id"]) for e in hits],
        })
        ans["sections"].append({
            "type": "tips",
            "items": ["本问题未命中精编答案库，以上为多路检索结果；可点击条目查看完整字段",
                      "更精确的口径请咨询 12366 或主管税务机关"],
        })
        ans["refs"] = [e["id"] for e in hits]
    if ans["risk"] == "high":
        ans["sections"].append({
            "type": "escalate",
            "text": "🔴 本问题涉及高风险事项（可能涉刑事或重大处罚），请尽快转介执业税务师/律师处理；本应用输出仅供参考。",
        })

    # Stage 1/2/4/5：五阶段编排、引用对齐校验、赵审计复核
    text = " ".join(str(s.get("text", "")) for s in ans["sections"] if isinstance(s, dict))
    pipe = orchestrator.run_pipeline(q, v5, {"mode": ans["mode"], "text": text},
                                     ans["refs"], ans["routed"], ans["risk"], ENTRY_MAP)
    ans["stage_trace"] = pipe["stages"]
    ans["verification"] = pipe["verification"]
    ans["audit"] = pipe["audit"]
    ans["confidence"] = pipe["confidence"]
    ans["abstain"] = pipe["abstain"]
    ans["_pipe"] = pipe
    warns = pipe["verification"]["warnings"]
    if warns:
        ans["sections"].append({"type": "tips", "title": "引用与时效校验提示",
                                "items": warns[:5]})
    # Stage 3b：深度解读（概念卡六段式 + 关联/边界/场景），不改动三段式主答案
    if mode == "deep":
        ans["deep"] = deep_dive.deep_payload(q, ENTRY_MAP)
        ans["deep_mode"] = True

    # ---- P0-2 溯源四要素：所有回答统一挂载 ----
    if ans.get("mode") not in ("abstain",) and ans.get("refs"):
        ans["sections"].append(provenance_block(ans["refs"], ans.get("mode", "")))

    # ---- 可信度引擎（L1 时效闸 / L2 权威 / L3 生成溯源 / L4 聚合） ----
    cited = [ENTRY_MAP[r] for r in ans.get("refs", []) if r in ENTRY_MAP]
    tr = trust.trust_report(q, text, cited, list(ENTRY_MAP.values()),
                            mode=ans.get("mode", ""))
    ans["trust"] = tr
    if tr["gate"] == "block":
        ans["sections"].insert(0, {
            "type": "escalate",
            "text": "🛑 可信度硬闸触发：" + "；".join(tr["warnings"][:2]) +
                    "（引用了过期/废止依据或存在未溯源断言，不得作为申报或合同依据）",
        })
    elif tr["warnings"]:
        # 与引用校验提示去重后并入
        existing = {w for w in warns}
        extra = [w for w in tr["warnings"] if w not in existing]
        if extra:
            ans["sections"].append({"type": "tips", "title": "可信度与时效提示",
                                    "items": extra[:5]})
    return ans


def ask_llm(q, local_ans):
    """可选：调用 OpenAI 兼容接口。失败时静默回退本地答案。"""
    if not (LLM.get("enabled") and LLM.get("api_key")):
        return None
    ctx_parts = []
    for eid in local_ans["refs"][:3]:
        e = ENTRY_MAP[eid]
        ctx_parts.append(f"【{e['title']}】时效性:{e['status']}\n核心条款:{e['fields'].get('核心条款','')[:600]}\n合规要点:{e['fields'].get('合规要点','')[:400]}")
    context = "\n\n".join(ctx_parts) or "（无命中条目）"
    sys_prompt = (
        "你是财税合规智能体。只依据给定知识库上下文回答，禁止编造法规名称、文号、数字门槛；"
        "上下文没有覆盖时明确说明「知识库暂无收录，请以官方渠道为准」。回答结构：结论→依据→风险提示。"
        "知识库核验日期为 2026-11-06，如涉及时效请提示用户复核。"
    )
    body = json.dumps({
        "model": LLM.get("model", "deepseek-chat"),
        "messages": [
            {"role": "system", "content": sys_prompt},
            {"role": "user", "content": f"知识库上下文：\n{context}\n\n用户问题：{q}"},
        ],
        "temperature": 0.2,
    }).encode("utf-8")
    base = LLM.get("base_url", "https://api.deepseek.com").rstrip("/")
    url = base + ("/chat/completions" if base.endswith("/v1") else "/v1/chat/completions")
    req = urllib.request.Request(url, data=body, headers={
        "Content-Type": "application/json",
        "Authorization": f"Bearer {LLM.get('api_key')}",
    })
    try:
        with urllib.request.urlopen(req, timeout=40) as resp:
            data = json.loads(resp.read().decode("utf-8"))
        content = data["choices"][0]["message"]["content"]
        return {"mode": "llm", "text": content, "refs": local_ans["refs"],
                "role": local_ans["role"], "routed": local_ans["routed"], "risk": local_ans["risk"]}
    except Exception as ex:
        print(f"[warn] llm call failed: {ex}")
        return None


# ---------------------------------------------------------------- http handler
CT_MAP = {".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8",
          ".js": "application/javascript; charset=utf-8", ".json": "application/json; charset=utf-8",
          ".svg": "image/svg+xml", ".png": "image/png", ".ico": "image/x-icon"}


class Handler(BaseHTTPRequestHandler):
    def log_message(self, fmt, *args):
        pass

    def _send(self, code, ctype, payload: bytes):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(payload)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        try:
            self.wfile.write(payload)
        except BrokenPipeError:
            pass

    def _json(self, obj, code=200):
        self._send(code, "application/json; charset=utf-8", json.dumps(obj, ensure_ascii=False).encode("utf-8"))

    def _static(self, name):
        path = os.path.normpath(os.path.join(STATIC, name))
        if not path.startswith(STATIC) or not os.path.isfile(path):
            self._send(404, "text/plain; charset=utf-8", b"not found")
            return
        ext = os.path.splitext(path)[1].lower()
        with open(path, "rb") as f:
            self._send(200, CT_MAP.get(ext, "application/octet-stream"), f.read())

    def do_GET(self):
        parsed = urlparse(self.path)
        path = unquote(parsed.path)
        if path in ("/", "/index.html"):
            self._static("index.html")
        elif path == "/api/meta":
            self._json(meta_payload())
        elif path == "/api/health":
            self._json({"ok": True, "entries": len(KB["entries"]), "kb_version": KB["kb_version"]})
        elif path == "/api/examples":
            self._json(examples_payload())
        elif path == "/api/kb":
            self._json(KB)
        elif path == "/api/business-cases":
            q = (parse_qs(parsed.query).get("q", [""])[0] or "").strip()
            self._json(RETRIEVER.retrieve_business_cases(q, topk=12))
        elif path == "/api/llm-context":
            qs = parse_qs(parsed.query)
            q = (qs.get("q", [""])[0] or "").strip()
            mode = (qs.get("mode", ["standard"])[0] or "standard").strip()
            if mode not in ("standard", "deep"):
                mode = "standard"
            if not q:
                self._json({"error": "empty question"}, 400)
                return
            self._json(build_llm_context(q, mode=mode))
        elif path == "/api/concepts":
            self._json(deep_dive.concepts_payload())
        elif path == "/api/concept":
            cid = (parse_qs(parsed.query).get("id", [""])[0] or "").strip()
            detail = deep_dive.concept_detail(cid) if cid else None
            self._json(detail or {"error": "concept not found"}, 404 if not detail else 200)
        elif path == "/api/scenarios":
            self._json(deep_dive.scenarios_payload())
        elif path == "/api/deep-dive":
            q = (parse_qs(parsed.query).get("q", [""])[0] or "").strip()
            self._json(deep_dive.deep_payload(q, ENTRY_MAP) if q else {"error": "empty question"})
        elif path == "/api/retrieve":
            qs = parse_qs(parsed.query)
            q = (qs.get("q", [""])[0] or "").strip()
            mode = (qs.get("mode", ["v5"])[0] or "v5").strip()
            if mode not in ("v5", "legacy"):
                mode = "v5"
            self._json(RETRIEVER.retrieve(q, mode=mode, topk=8))
        elif path == "/api/metrics":
            self._json(metrics_payload())
        elif path == "/api/search":
            qs = parse_qs(parsed.query)
            q = (qs.get("q", [""])[0] or "").strip()
            if not q:
                self._json({"results": []})
                return
            rr = RETRIEVER.retrieve(q, mode="v5", topk=12)
            results = []
            for h in rr["hits"]:
                e = ENTRY_MAP.get(h["id"])
                if not e:
                    continue
                pos = e["search_text"].find(q[:2])
                preview = e["body_md"][:140] if pos < 0 else e["search_text"][max(0, pos - 20): pos + 100]
                results.append({"id": e["id"], "no": e["no"], "title": e["title"],
                                "category": e["category"], "status": e["status"],
                                "score": h["score"], "preview": preview,
                                "tier": h.get("tier", ""), "entry_type": h.get("entry_type", "")})
            self._json({"results": results, "mode": "v5",
                        "confidence": rr["confidence"], "abstain": rr["abstain"]})
        else:
            self._static(path.lstrip("/"))

    def do_POST(self):
        parsed = urlparse(self.path)
        if parsed.path == "/api/reconcile":
            try:
                length = int(self.headers.get("Content-Length", 0))
                body = json.loads(self.rfile.read(length) or b"{}") if length else {}
                from reconcile import reconcile as _rc, render_report as _rr
                res = _rc(body.get("invoices") or [], body.get("bank") or [],
                          body.get("contracts") or [])
                html_path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                                         "reports", "reconcile-last.html")
                try:
                    _rr(res, html_path)
                    res["report_path"] = html_path
                except Exception:
                    pass
                self._json(res)
            except Exception as exc:  # noqa: BLE001
                self._json({"error": str(exc)}, 500)
            return
        if parsed.path == "/api/checklist":
            try:
                from checklist import generate as _gen
                body = {}
                length = int(self.headers.get("Content-Length", 0))
                if length:
                    body = json.loads(self.rfile.read(length) or b"{}")
                out = _gen(body.get("enterprise_type", "一般纳税人"),
                           body.get("tax_types") or None,
                           body.get("region", "全国"))
                self._json(out)
            except Exception as exc:  # noqa: BLE001
                self._json({"error": str(exc)}, 500)
            return
        if parsed.path == "/api/trust-check":
            try:
                length = int(self.headers.get("Content-Length", 0))
                body = json.loads(self.rfile.read(length) or b"{}") if length else {}
                text = str(body.get("text") or "")
                refs = body.get("refs") or []
                cited = [ENTRY_MAP[r] for r in refs if r in ENTRY_MAP]
                tr = trust.trust_report(body.get("q", ""), text, cited,
                                        list(ENTRY_MAP.values()), mode="llm")
                self._json(tr)
            except Exception as exc:  # noqa: BLE001
                self._json({"error": str(exc)}, 500)
            return
        if parsed.path != "/api/ask":
            self._json({"error": "unknown endpoint"}, 404)
            return
        try:
            length = int(self.headers.get("Content-Length", 0))
            payload = json.loads(self.rfile.read(length).decode("utf-8") or "{}")
            q = (payload.get("q") or "").strip()
            mode = (payload.get("mode") or "standard").strip()
            if mode not in ("standard", "deep"):
                mode = "standard"
            if not q:
                self._json({"error": "empty question"}, 400)
                return
            local_ans = ask_local(q, mode=mode)
            llm_ans = ask_llm(q, local_ans)
            answer = llm_ans if llm_ans else local_ans
            if llm_ans:
                for k in ("stage_trace", "verification", "audit", "confidence", "abstain",
                          "deep", "deep_mode"):
                    answer[k] = local_ans.get(k)
            answer.pop("_pipe", None)
            log_query(q, local_ans)
            out = {
                "q": q,
                "answer": answer,
                "disclaimer": "本回答基于本地知识库（核验日期 2026-11-07）生成，仅供合规参考，不构成税务师/律师专业意见；正式用途请以官方原文为准。",
            }
            self._json(out)
        except Exception as ex:
            self._json({"error": str(ex)}, 500)


def main():
    srv = ThreadingHTTPServer(("127.0.0.1", PORT), Handler)
    print(f"[ok] tax-compliance agent serving at http://localhost:{PORT}")
