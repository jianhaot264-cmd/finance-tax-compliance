def score_entry(q, e):
    grams = set()
    for i in range(len(q) - 1):
        grams.add(q[i:i + 2])
    for i in range(len(q) - 2):
        grams.add(q[i:i + 3])
    grams = {g for g in grams if g not in STOP and not re.match(r"^[\W\d]+$", g)}
    title = e["title"] + e["heading"]
    s = 0
    for g in grams:
        if g in title:
            s += 3
        elif g in e["search_text"]:
            s += 1
    return s


def retrieve(q, top=3):
    scored = [(score_entry(q, e), e) for e in KB["entries"]]
    scored = [x for x in scored if x[0] > 0]
    scored.sort(key=lambda x: -x[0])
    return [e for _, e in scored[:top]]


